"""Generate the OpenCode configuration fragment for a RAPTOR checkout.

The fragment is intentionally minimal: it references the generated
``AGENTS.md``, exports the environment RAPTOR's scripts expect, allows the
generated skills despite the user's global ``skill * deny`` rule, forwards any
``.mcp.json`` servers and wires the guard plugin. Fields that OpenCode cannot
merge automatically are documented in ``merge_notes.md``.
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from .errors import GenerationError
from .paths import raptor_home as resolve_raptor_home

FRAGMENT_NAME = "opencode.fragment.jsonc"
NOTES_NAME = "merge_notes.md"
PLUGIN_RELATIVE = "plugins/raptor-guard.ts"
SKILL_ALLOW_ANY = "raptor-*"
RAPTOR_HOME_REF = "{env:RAPTOR_HOME}"

_HEADER = (
    "// Generated by raptor-opencode. Do not edit by hand: regenerate instead.\n"
    "// Merge these fields into your global ~/.config/opencode/opencode.jsonc.\n"
    "// See merge_notes.md for the fields that need manual reconciliation.\n"
)


def build_fragment(
    raptor_home: str | Path,
    skill_names: Sequence[str],
    *,
    install_home: str | Path | None = None,
) -> dict[str, Any]:
    """Return the configuration fragment as a plain dictionary.

    Paths use ``{env:RAPTOR_HOME}`` so the fragment stays portable and never
    embeds a development checkout passed via ``--raptor-home``. ``install_home``
    is the actual path exported as ``RAPTOR_HOME``; when omitted it is resolved
    from the environment (or the XDG default).
    """
    root = Path(raptor_home)
    resolved_home = str(install_home) if install_home is not None else str(resolve_raptor_home())
    fragment: dict[str, Any] = {
        "instructions": [f"{RAPTOR_HOME_REF}/AGENTS.md"],
        "env": {
            "RAPTOR_HOME": resolved_home,
            "CLAUDE_ENV_FILE": f"{RAPTOR_HOME_REF}/.claude/raptor.env",
            "CLAUDECODE": "1",
            "CLAUDE_BASH_MAINTAIN_PROJECT_WORKING_DIR": "1",
            "BASH_DEFAULT_TIMEOUT_MS": "300000",
            "PATH": f"{RAPTOR_HOME_REF}/libexec:{{env:PATH}}",
        },
        "permissions": _permissions(skill_names),
    }
    servers = load_mcp_servers(root)
    if servers is not None:
        fragment["mcp"] = {"servers": servers}
    fragment["plugin"] = [PLUGIN_RELATIVE]
    return fragment


def render_fragment(fragment: Mapping[str, Any]) -> str:
    """Render *fragment* as valid JSONC (a comment header plus strict JSON)."""
    return _HEADER + json.dumps(fragment, indent=2, ensure_ascii=False) + "\n"


def load_mcp_servers(raptor_home: str | Path) -> dict[str, Any] | None:
    """Translate ``<raptor_home>/.mcp.json``; return ``None`` when absent."""
    path = Path(raptor_home) / ".mcp.json"
    if not path.is_file():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise GenerationError(f"{path}: invalid JSON ({exc})") from exc
    if not isinstance(data, Mapping):
        raise GenerationError(f"{path}: expected a JSON object")
    raw = data.get("mcpServers", data.get("servers"))
    if raw is None:
        return {}
    if not isinstance(raw, Mapping):
        raise GenerationError(f"{path}: 'mcpServers' must be an object")
    servers: dict[str, Any] = {}
    for name, server in raw.items():
        if not isinstance(server, Mapping):
            raise GenerationError(f"{path}: server {name!r} must be an object")
        servers[str(name)] = _translate_server(str(name), server)
    return servers


def write_config(
    raptor_home: str | Path,
    out_dir: str | Path,
    skill_names: Sequence[str],
    *,
    install_home: str | Path | None = None,
    dry_run: bool = False,
) -> tuple[Path, Path]:
    """Write ``opencode.fragment.jsonc`` and ``merge_notes.md`` under *out_dir*.

    Returns the fragment and notes paths, whether or not anything was written.
    Nothing outside *out_dir* is touched.
    """
    fragment = build_fragment(raptor_home, skill_names, install_home=install_home)
    directory = Path(out_dir)
    fragment_path = directory / FRAGMENT_NAME
    notes_path = directory / NOTES_NAME
    if dry_run:
        return fragment_path, notes_path
    directory.mkdir(parents=True, exist_ok=True)
    fragment_path.write_text(render_fragment(fragment), encoding="utf-8")
    notes_path.write_text(render_notes(fragment), encoding="utf-8")
    return fragment_path, notes_path


def render_notes(fragment: Mapping[str, Any]) -> str:
    """Explain how to merge the fragment by hand."""
    env = fragment.get("env", {})
    permissions = fragment.get("permissions", [])
    lines = [
        "# Merging `opencode.fragment.jsonc`",
        "",
        "OpenCode does not merge a second configuration file automatically. Copy "
        "the keys below into your `~/.config/opencode/opencode.jsonc` (or your "
        "project-level `opencode.jsonc`) and restart OpenCode.",
        "",
        "## `instructions`",
        "",
        "- Points at `{env:RAPTOR_HOME}/AGENTS.md`, so the fragment stays portable.",
        "- Export `RAPTOR_HOME` (or keep the default `~/.local/share/raptor`) and "
        "regenerate if that location changes.",
        "",
        "## `env`",
        "",
        "These variables apply to the **OpenCode process and the tools it spawns**, "
        "not to your interactive shell:",
        "",
    ]
    lines.extend(f"- `{key}={value}`" for key, value in env.items())
    lines.extend(
        [
            "",
            "`RAPTOR_HOME` is the resolved installation path (from the environment or "
            "the XDG default); it deliberately ignores `--raptor-home`, which is only "
            "a generation-time source. `PATH` prepends `<RAPTOR_HOME>/libexec` so the "
            "`raptor-*` commands resolve. The `{env:PATH}` part expands to the "
            "inherited `PATH`.",
            "",
            "## `permissions`",
            "",
            "Your global configuration denies every skill (`skill * deny`). These "
            "entries re-allow only RAPTOR's skills:",
            "",
        ]
    )
    lines.extend(f"- `{item['resource']}`" for item in permissions)
    lines.extend(
        [
            "",
            "Keep the `raptor-*` wildcard so renamed skills remain allowed after regeneration.",
            "",
            "## `plugin`",
            "",
            f"- `{fragment.get('plugin', [''])[0]}` runs the guard plugin, resolved "
            "relative to your OpenCode config directory. It is generated by a "
            "different module; regenerate before starting OpenCode.",
            "",
            "## Hook policy",
            "",
            "`raptor-policy.json` mirrors the PreToolUse hooks of each agent and bakes "
            "the absolute `raptor_home` used at generation time. Empty `bash` or "
            "`webfetch` rules mean the agent had no such hook in Claude Code, so the "
            "guard leaves that tool unrestricted (parity). Agents without a policy "
            "entry behave the same way and log once. Sessions whose agent was never "
            "reported by `chat.params` are blocked unless `default.unrestricted` is "
            "`true`; the generated default is `false`, so the guard fails closed.",
            "",
        ]
    )
    if "mcp" in fragment:
        lines.extend(
            [
                "## `mcp`",
                "",
                "Servers were translated from `<RAPTOR_HOME>/.mcp.json`. Review them "
                "and drop any server you do not want inside OpenCode.",
                "",
            ]
        )
    else:
        lines.extend(
            [
                "## `mcp`",
                "",
                "No `<RAPTOR_HOME>/.mcp.json` was found, so this key is omitted.",
                "",
            ]
        )
    return "\n".join(lines).rstrip() + "\n"


def _permissions(skill_names: Sequence[str]) -> list[dict[str, str]]:
    resources: list[str] = [SKILL_ALLOW_ANY]
    for name in skill_names:
        if name and name not in resources:
            resources.append(name)
    return [{"action": "skill", "resource": resource, "effect": "allow"} for resource in resources]


def _translate_server(name: str, server: Mapping[str, Any]) -> dict[str, Any]:
    url = server.get("url")
    if isinstance(url, str) and url.strip():
        entry: dict[str, Any] = {"type": "remote", "url": url.strip()}
        headers = server.get("headers")
        if isinstance(headers, Mapping) and headers:
            entry["headers"] = {str(key): str(value) for key, value in headers.items()}
        return entry

    command = server.get("command")
    if isinstance(command, str) and command.strip():
        argv = [command.strip()]
    elif isinstance(command, Sequence) and not isinstance(command, str | bytes):
        argv = [str(part) for part in command]
    else:
        raise GenerationError(f"MCP server {name!r} has neither 'url' nor 'command'")
    args = server.get("args")
    if isinstance(args, Sequence) and not isinstance(args, str | bytes):
        argv.extend(str(part) for part in args)
    entry = {"type": "local", "command": argv}
    environment = server.get("env")
    if isinstance(environment, Mapping) and environment:
        entry["environment"] = {str(key): str(value) for key, value in environment.items()}
    return entry


