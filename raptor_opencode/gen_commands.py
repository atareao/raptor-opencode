"""Convert Claude Code slash commands into thin OpenCode command wrappers.

The generated command deliberately does not copy RAPTOR's instructions: it
points the model at the original file inside ``$RAPTOR_HOME`` and tells it to
honour RAPTOR's dispatch rules. That keeps the 37 commands of v3.1.0 in sync with
upstream and guarantees operator arguments reach RAPTOR untouched.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .errors import GenerationError
from .gen_agents import slugify
from .parse_claude import dump_frontmatter, parse_file

_WRAPPER_TEMPLATE = (
    "# /{slug}\n"
    "\n"
    "Thin wrapper generated by raptor-opencode. RAPTOR's own definition is authoritative.\n"
    "\n"
    "1. Read `$RAPTOR_HOME/.claude/commands/{slug}.md` in full before doing anything else. "
    "Use both its frontmatter and its body; do not reconstruct the steps from memory.\n"
    "2. Apply RAPTOR's dispatch rules from `$RAPTOR_HOME/AGENTS.md` "
    "(the port of upstream `CLAUDE.md`):\n"
    "   - `dispatch: skill`: the command body is a multi-step workflow. "
    "Follow its steps and run only the libexec/CLI commands it names.\n"
    "   - `dispatch: <command-line>`: substitute the operator's arguments and run exactly "
    "that command. Do not add pipes, redirects, extra flags, wrappers, `cd` prefixes, "
    "or environment-variable prefixes.\n"
    "3. Pass the user's arguments through verbatim as `$ARGUMENTS`: no filtering, "
    "no rewriting, no added flags, and no quoting or escaping changes.\n"
    "\n"
    "Declared dispatch: `{dispatch}`\n"
)


@dataclass(frozen=True, slots=True)
class Command:
    """A generated OpenCode command file."""

    slug: str
    content: str
    source: Path


def load_commands(commands_dir: Path) -> list[Command]:
    """Load every ``*.md`` in *commands_dir*, sorted by filename."""
    if not commands_dir.is_dir():
        return []
    commands = [command_from_file(path) for path in sorted(commands_dir.glob("*.md"))]
    seen: dict[str, Path] = {}
    for command in commands:
        if command.slug in seen:
            raise GenerationError(
                f"duplicate command slug {command.slug!r}: "
                f"{seen[command.slug]} and {command.source}"
            )
        seen[command.slug] = command.source
    return commands


def command_from_file(path: Path) -> Command:
    """Read *path* and build the corresponding OpenCode command wrapper."""
    frontmatter, _body = parse_file(path)
    slug = slugify(path.stem)
    return Command(slug=slug, content=render_command(frontmatter, slug), source=path)


def render_command(frontmatter: dict[str, Any], slug: str) -> str:
    """Render an OpenCode command wrapper for *slug*."""
    description = frontmatter.get("description")
    if not isinstance(description, str) or not description.strip():
        raise GenerationError(f"command {slug!r} is missing a 'description' field")

    data: dict[str, Any] = {"description": description.strip()}
    hint = frontmatter.get("argument-hint")
    if isinstance(hint, str) and hint.strip():
        data["argument-hint"] = hint.strip()

    dispatch = frontmatter.get("dispatch")
    if isinstance(dispatch, str) and dispatch.strip():
        dispatch_text = dispatch.strip()
    elif dispatch is None:
        dispatch_text = "missing (inspect the original frontmatter)"
    else:
        dispatch_text = str(dispatch)

    body = _WRAPPER_TEMPLATE.format(slug=slug, dispatch=dispatch_text)
    return f"{dump_frontmatter(data)}\n\n{body}"
