"""Port RAPTOR's ``CLAUDE.md`` to an OpenCode ``AGENTS.md``.

Only the path conventions that differ between Claude Code and this adapter are
rewritten. Prose that mentions Claude Code is left untouched: it documents the
upstream behaviour and remains accurate.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

from .errors import GenerationError

AGENTS_MD_NAME = "AGENTS.md"
SOURCE_NAME = "CLAUDE.md"
DEFAULT_TAG = "unknown"

_CLAUDE_PROJECT_DIR = re.compile(r"\$\{?CLAUDE_PROJECT_DIR\}?")
_HOME_CLAUDE = re.compile(r"~/\.claude")
# Do not double-prefix paths that already point inside a checkout.
_RELATIVE_CLAUDE = re.compile(r"(?<![\w./$~-])\.claude/")
# ``libexec/`` only becomes absolute when it names a script (a bare
# ``libexec/`` directory mention in prose must stay as written).
_RELATIVE_LIBEXEC = re.compile(r"(?<![\w./$~-])libexec/(?=[\w.-])")

_HEADER = (
    "<!-- Generated by raptor-opencode from RAPTOR {tag}; do not edit by hand. -->\n"
    "<!-- Re-run `raptor-opencode generate` (or `install`) to refresh it. -->\n"
    "<!-- Upstream CLAUDE.md is the source of truth; send changes there. -->\n"
)


def rewrite_paths(text: str) -> str:
    """Rewrite Claude-specific paths without touching prose or line breaks."""
    text = _CLAUDE_PROJECT_DIR.sub("$RAPTOR_HOME", text)
    text = _HOME_CLAUDE.sub("$RAPTOR_HOME", text)
    text = _RELATIVE_CLAUDE.sub("$RAPTOR_HOME/.claude/", text)
    text = _RELATIVE_LIBEXEC.sub("$RAPTOR_HOME/libexec/", text)
    return text


def find_unrewritten_paths(text: str) -> list[str]:
    """Return Claude-relative paths that OpenCode cannot resolve.

    Each entry names the line and the convention it found, so ``doctor`` can
    explain a rewriter regression instead of only failing.
    """
    problems: list[str] = []
    for number, line in enumerate(text.splitlines(), 1):
        if _RELATIVE_CLAUDE.search(line):
            problems.append(f"line {number}: relative .claude/ path")
        if _RELATIVE_LIBEXEC.search(line):
            problems.append(f"line {number}: libexec/ without $RAPTOR_HOME prefix")
    return problems


def render_agents_md(source: str, *, tag: str = DEFAULT_TAG) -> str:
    """Return the full ``AGENTS.md`` document for *source*."""
    header = _HEADER.format(tag=tag)
    body = rewrite_paths(source)
    if body and not body.endswith("\n"):
        body += "\n"
    return header + "\n" + body


def detect_tag(raptor_home: str | Path) -> str:
    """Return the checkout's git tag/commit, or ``unknown`` outside a repo."""
    try:
        result = subprocess.run(
            ["git", "-C", str(raptor_home), "describe", "--tags", "--always"],
            check=False,
            capture_output=True,
            text=True,
        )
    except OSError:
        return DEFAULT_TAG
    if result.returncode != 0:
        return DEFAULT_TAG
    return result.stdout.strip() or DEFAULT_TAG


def generate_agents_md(
    raptor_home: str | Path,
    out_dir: str | Path,
    *,
    tag: str = DEFAULT_TAG,
    dry_run: bool = False,
) -> Path:
    """Write ``<out_dir>/AGENTS.md`` translated from ``<raptor_home>/CLAUDE.md``."""
    source_path = Path(raptor_home) / SOURCE_NAME
    destination = Path(out_dir) / AGENTS_MD_NAME
    if not source_path.is_file():
        raise GenerationError(
            f"missing {source_path}; RAPTOR v3.1.0 ships CLAUDE.md at the checkout root"
        )
    if dry_run:
        return destination
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        render_agents_md(source_path.read_text(encoding="utf-8"), tag=tag),
        encoding="utf-8",
    )
    return destination


__all__ = [
    "AGENTS_MD_NAME",
    "DEFAULT_TAG",
    "SOURCE_NAME",
    "detect_tag",
    "find_unrewritten_paths",
    "generate_agents_md",
    "render_agents_md",
    "rewrite_paths",
]
