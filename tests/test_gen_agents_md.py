"""Tests for the ``CLAUDE.md`` → ``AGENTS.md`` port."""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from raptor_opencode.errors import GenerationError
from raptor_opencode.gen_agents_md import (
    DEFAULT_TAG,
    generate_agents_md,
    render_agents_md,
    rewrite_paths,
)

RAPTOR_SRC = Path("/tmp/opencode/raptor-src")

# Constructions copied from RAPTOR v3.1.0's CLAUDE.md: prose, backticked
# paths, a table row, fenced commands and a bare ``libexec/`` directory
# mention. Each one must survive (or be rewritten) exactly once.
FIXTURE = """\
# RAPTOR - Autonomous Offensive/Defensive Research Framework

Safe operations (install, scan, read, generate): DO IT.

## SLASH-COMMAND DISPATCH

1. Read `.claude/commands/<name>.md` frontmatter.
2. When unsure, check `ls libexec/raptor-<name>*` — do not guess names.
3. Project root: `$CLAUDE_PROJECT_DIR` and `${CLAUDE_PROJECT_DIR}`.

| Command | Entry point |
|---|---|
| `/audit` | `libexec/raptor-audit` |
| `/scan` | `python3 raptor.py scan` |

```bash
libexec/raptor-run-lifecycle start audit --target "$TARGET"
~/.claude/settings.json
```

Settings live in `~/.claude/settings.json`; Claude Code reads them.
Already absolute: `$RAPTOR_HOME/.claude/skills/code-understanding/SKILL.md`.
SAGE docs use `core/sage/CLAUDE.md` and stay untouched.
Verification harnesses never live on the `libexec/` dispatch surface.
"""

_STRAY_RELATIVE_CLAUDE = re.compile(r"(?<![\w./$~-])\.claude/")
_STRAY_RELATIVE_LIBEXEC = re.compile(r"(?<![\w./$~-])libexec/(?=[\w.-])")


def test_rewrite_paths_preserves_line_count() -> None:
    source = FIXTURE
    rewritten = rewrite_paths(source)
    assert len(rewritten.splitlines()) == len(source.splitlines())


def test_rewrite_paths_translates_only_the_documented_conventions() -> None:
    rewritten = rewrite_paths(FIXTURE)

    assert "`$RAPTOR_HOME/.claude/commands/<name>.md`" in rewritten
    assert "`ls $RAPTOR_HOME/libexec/raptor-<name>*`" in rewritten
    assert "`$RAPTOR_HOME` and `$RAPTOR_HOME`" in rewritten
    assert "| `$RAPTOR_HOME/libexec/raptor-audit` |" in rewritten
    assert "libexec/raptor-run-lifecycle" in rewritten
    assert "~/.claude" not in rewritten
    assert "$RAPTOR_HOME/RAPTOR_HOME" not in rewritten


def test_rewrite_paths_leaves_prose_and_claude_code_mentions_alone() -> None:
    rewritten = rewrite_paths(FIXTURE)
    assert "Claude Code reads them." in rewritten
    assert "core/sage/CLAUDE.md" in rewritten
    assert "never live on the `libexec/` dispatch surface" in rewritten


def test_rewrite_paths_does_not_double_prefix_absolute_paths() -> None:
    rewritten = rewrite_paths(FIXTURE)
    assert "$RAPTOR_HOME/$RAPTOR_HOME" not in rewritten
    assert "$RAPTOR_HOME/.claude/skills/code-understanding/SKILL.md" in rewritten


def test_rewritten_document_has_no_stray_relative_paths() -> None:
    rewritten = rewrite_paths(FIXTURE)
    assert not _STRAY_RELATIVE_CLAUDE.search(rewritten)
    assert not _STRAY_RELATIVE_LIBEXEC.search(rewritten)


def test_render_adds_three_header_lines() -> None:
    rendered = render_agents_md(FIXTURE, tag="v3.1.0")
    lines = rendered.splitlines()

    assert lines[0].startswith("<!-- Generated by raptor-opencode from RAPTOR v3.1.0")
    assert "do not edit" in lines[0]
    assert "refresh" in lines[1]
    assert "source of truth" in lines[2]
    assert lines[3] == ""
    assert len(lines) == len(FIXTURE.splitlines()) + 4


def test_render_defaults_to_unknown_tag() -> None:
    rendered = render_agents_md("Body\n")
    assert f"RAPTOR {DEFAULT_TAG}" in rendered


def test_generate_writes_agents_md_inside_out_dir(tmp_path: Path) -> None:
    raptor_home = tmp_path / "raptor"
    raptor_home.mkdir()
    (raptor_home / "CLAUDE.md").write_text(FIXTURE, encoding="utf-8")
    out = tmp_path / "out"

    destination = generate_agents_md(raptor_home, out, tag="v3.1.0")

    assert destination == out / "AGENTS.md"
    assert destination.read_text(encoding="utf-8").startswith(
        "<!-- Generated by raptor-opencode from RAPTOR v3.1.0"
    )
    assert sorted(path.name for path in out.iterdir()) == ["AGENTS.md"]


def test_generate_dry_run_writes_nothing(tmp_path: Path) -> None:
    raptor_home = tmp_path / "raptor"
    raptor_home.mkdir()
    (raptor_home / "CLAUDE.md").write_text(FIXTURE, encoding="utf-8")
    out = tmp_path / "out"

    destination = generate_agents_md(raptor_home, out, dry_run=True)

    assert destination == out / "AGENTS.md"
    assert not out.exists()


def test_generate_rejects_a_missing_claude_md(tmp_path: Path) -> None:
    with pytest.raises(GenerationError, match="missing .*CLAUDE.md"):
        generate_agents_md(tmp_path, tmp_path / "out")


@pytest.mark.skipif(
    not (RAPTOR_SRC / "CLAUDE.md").is_file(),
    reason="real RAPTOR checkout not available",
)
def test_upstream_claude_md_ports_cleanly() -> None:
    source = (RAPTOR_SRC / "CLAUDE.md").read_text(encoding="utf-8")
    rewritten = rewrite_paths(source)

    assert len(rewritten.splitlines()) == len(source.splitlines())
    assert not _STRAY_RELATIVE_CLAUDE.search(rewritten)
    assert not _STRAY_RELATIVE_LIBEXEC.search(rewritten)
    assert "~/.claude" not in rewritten
    assert "Claude Code" in rewritten
